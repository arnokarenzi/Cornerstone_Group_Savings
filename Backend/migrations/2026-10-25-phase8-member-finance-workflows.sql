-- CORNESTONE Phase 8: member payment submissions, member-originated loan applications,
-- and controlled committee role management. Additive only; existing financial records are preserved.

CREATE TABLE IF NOT EXISTS member_payment_submissions (
  id BIGINT NOT NULL AUTO_INCREMENT,
  group_id INT NOT NULL,
  cycle_id INT NOT NULL,
  member_id INT NOT NULL,
  purpose ENUM('SHARE_PURCHASE','LOAN_REPAYMENT','FINE_PAYMENT') NOT NULL,
  amount DECIMAL(12,2) NOT NULL,
  shares_count INT NOT NULL DEFAULT 0,
  share_value_at_submission DECIMAL(12,2) NULL,
  loan_id INT NULL,
  fine_assessment_id BIGINT NULL,
  meeting_id INT NULL,
  payment_method ENUM('CASH_TO_COMMITTEE','BANK_TRANSFER','OTHER_MANUAL') NOT NULL,
  transfer_reference VARCHAR(150) NULL,
  notes VARCHAR(1000) NOT NULL,
  intended_recipient_user_id INT NOT NULL,
  status ENUM('REQUESTED','APPROVED','REJECTED') NOT NULL DEFAULT 'REQUESTED',
  requested_by INT NOT NULL,
  verified_by INT NULL,
  verified_at TIMESTAMP NULL DEFAULT NULL,
  decision_notes VARCHAR(1000) NULL,
  transaction_id BIGINT NULL,
  receipt_id BIGINT NULL,
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  PRIMARY KEY (id),
  UNIQUE KEY uq_member_payment_group_reference (group_id, transfer_reference),
  UNIQUE KEY uq_member_payment_transaction (transaction_id),
  UNIQUE KEY uq_member_payment_receipt (receipt_id),
  KEY idx_member_payment_cycle_status (group_id, cycle_id, status, id),
  KEY idx_member_payment_member_cycle (member_id, cycle_id, status),
  KEY idx_member_payment_recipient_status (intended_recipient_user_id, status, id),
  KEY idx_member_payment_loan (loan_id, status),
  KEY idx_member_payment_fine (fine_assessment_id, status),
  CONSTRAINT fk_member_payment_group FOREIGN KEY (group_id) REFERENCES `groups`(id) ON DELETE CASCADE,
  CONSTRAINT fk_member_payment_cycle FOREIGN KEY (cycle_id) REFERENCES cycles(id) ON DELETE CASCADE,
  CONSTRAINT fk_member_payment_member FOREIGN KEY (member_id) REFERENCES users(id) ON DELETE RESTRICT,
  CONSTRAINT fk_member_payment_recipient FOREIGN KEY (intended_recipient_user_id) REFERENCES users(id) ON DELETE RESTRICT,
  CONSTRAINT fk_member_payment_requester FOREIGN KEY (requested_by) REFERENCES users(id) ON DELETE RESTRICT,
  CONSTRAINT fk_member_payment_verifier FOREIGN KEY (verified_by) REFERENCES users(id) ON DELETE SET NULL,
  CONSTRAINT fk_member_payment_loan FOREIGN KEY (loan_id) REFERENCES loans(id) ON DELETE RESTRICT,
  CONSTRAINT fk_member_payment_fine FOREIGN KEY (fine_assessment_id) REFERENCES fine_assessments(id) ON DELETE RESTRICT,
  CONSTRAINT fk_member_payment_meeting FOREIGN KEY (meeting_id) REFERENCES meetings(id) ON DELETE SET NULL,
  CONSTRAINT fk_member_payment_transaction FOREIGN KEY (transaction_id) REFERENCES transactions(id) ON DELETE SET NULL,
  CONSTRAINT fk_member_payment_receipt FOREIGN KEY (receipt_id) REFERENCES financial_receipts(id) ON DELETE SET NULL,
  CONSTRAINT chk_member_payment_amount CHECK (amount > 0 AND shares_count >= 0),
  CONSTRAINT chk_member_payment_purpose CHECK ((purpose = 'SHARE_PURCHASE' AND shares_count > 0 AND share_value_at_submission > 0 AND loan_id IS NULL AND fine_assessment_id IS NULL AND meeting_id IS NOT NULL) OR (purpose = 'LOAN_REPAYMENT' AND shares_count = 0 AND loan_id IS NOT NULL AND fine_assessment_id IS NULL) OR (purpose = 'FINE_PAYMENT' AND shares_count = 0 AND loan_id IS NULL AND fine_assessment_id IS NOT NULL AND meeting_id IS NULL))
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_general_ci;

CREATE TABLE IF NOT EXISTS loan_applications (
  id BIGINT NOT NULL AUTO_INCREMENT,
  group_id INT NOT NULL,
  cycle_id INT NOT NULL,
  member_id INT NOT NULL,
  requested_principal DECIMAL(12,2) NOT NULL,
  requested_term_days INT NOT NULL,
  reason VARCHAR(1000) NOT NULL,
  status ENUM('REQUESTED','APPROVED','REJECTED','DISBURSED','CANCELLED') NOT NULL DEFAULT 'REQUESTED',
  requested_by INT NOT NULL,
  reviewed_by INT NULL,
  reviewed_at TIMESTAMP NULL DEFAULT NULL,
  decision_notes VARCHAR(1000) NULL,
  loan_id INT NULL,
  disbursed_by INT NULL,
  disbursed_at TIMESTAMP NULL DEFAULT NULL,
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  PRIMARY KEY (id),
  UNIQUE KEY uq_loan_application_loan (loan_id),
  KEY idx_loan_app_group_cycle_status (group_id, cycle_id, status, id),
  KEY idx_loan_app_member_cycle (member_id, cycle_id, status),
  CONSTRAINT fk_loan_app_group FOREIGN KEY (group_id) REFERENCES `groups`(id) ON DELETE CASCADE,
  CONSTRAINT fk_loan_app_cycle FOREIGN KEY (cycle_id) REFERENCES cycles(id) ON DELETE CASCADE,
  CONSTRAINT fk_loan_app_member FOREIGN KEY (member_id) REFERENCES users(id) ON DELETE RESTRICT,
  CONSTRAINT fk_loan_app_requester FOREIGN KEY (requested_by) REFERENCES users(id) ON DELETE RESTRICT,
  CONSTRAINT fk_loan_app_reviewer FOREIGN KEY (reviewed_by) REFERENCES users(id) ON DELETE SET NULL,
  CONSTRAINT fk_loan_app_loan FOREIGN KEY (loan_id) REFERENCES loans(id) ON DELETE SET NULL,
  CONSTRAINT fk_loan_app_disburser FOREIGN KEY (disbursed_by) REFERENCES users(id) ON DELETE SET NULL,
  CONSTRAINT chk_loan_app_amount CHECK (requested_principal > 0),
  CONSTRAINT chk_loan_app_term CHECK (requested_term_days > 0 AND requested_term_days <= 3660)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_general_ci;
